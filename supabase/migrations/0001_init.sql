create or replace function public.award_achievement(p_user uuid, p_achievement text)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_points integer;
  v_inserted boolean;
begin
  if not exists (select 1 from public.achievements where id = p_achievement) then
    return 0;
  end if;

  insert into public.user_achievements (user_id, achievement_id)
  values (p_user, p_achievement)
  on conflict (user_id, achievement_id) do nothing;

  v_inserted := found;
  if not v_inserted then
    return 0;
  end if;

  select points into v_points from public.achievements where id = p_achievement;
  update public.profiles set points = points + coalesce(v_points, 0) where id = p_user;
  return coalesce(v_points, 0);
end;
$$;

create or replace function public.get_daily_challenge_ids(p_date date default current_date)
returns text[]
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(array_agg(id), '{}')
  from (
    select id
    from public.artworks
    where status = 'approved'
    order by md5(p_date::text || id)
    limit 5
  ) as picked;
$$;

-- The single server-side entry point for voting. Never compute points in the
-- browser. Returns a JSON object; the client should treat it as opaque data.
create or replace function public.cast_vote(p_artwork_id text, p_vote_type text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_profile public.profiles%rowtype;
  v_artwork public.artworks%rowtype;
  v_today date := (now() at time zone 'utc')::date;
  v_streak integer;
  v_points integer := 10;
  v_bonus integer := 0;
  v_awarded text[] := '{}';
  v_achievement_points integer;
  v_challenge_ids text[];
  v_challenge_count integer;
  v_challenge_complete boolean := false;
  v_votes integer;
  v_categories integer;
  v_total_users integer;
  v_higher_users integer;
begin
  if v_user is null then
    return jsonb_build_object('ok', false, 'code', 'unauthorized', 'message', 'Войдите, чтобы голосовать.');
  end if;

  if p_vote_type not in ('yes', 'no', 'unsure') then
    return jsonb_build_object('ok', false, 'code', 'invalid', 'message', 'Выберите один из трёх вариантов ответа.');
  end if;

  select * into v_profile from public.profiles where id = v_user for update;
  if not found then
    return jsonb_build_object('ok', false, 'code', 'unauthorized', 'message', 'Профиль не найден.');
  end if;
  if v_profile.is_blocked then
    return jsonb_build_object('ok', false, 'code', 'blocked', 'message', 'Эта учётная запись заблокирована.');
  end if;

  select * into v_artwork from public.artworks where id = p_artwork_id and status = 'approved';
  if not found then
    return jsonb_build_object('ok', false, 'code', 'not_found', 'message', 'Эта работа недоступна.');
  end if;

  if exists (select 1 from public.votes where user_id = v_user and artwork_id = p_artwork_id) then
    return jsonb_build_object('ok', false, 'code', 'already_voted', 'message', 'Вы уже оценили эту работу.');
  end if;

  begin
    insert into public.votes (user_id, artwork_id, vote_type)
    values (v_user, p_artwork_id, p_vote_type);
  exception when unique_violation then
    return jsonb_build_object('ok', false, 'code', 'already_voted', 'message', 'Вы уже оценили эту работу.');
  end;

  -- Streak: one increment per UTC day.
  if v_profile.last_vote_date = v_today then
    v_streak := greatest(v_profile.streak, 1);
  elsif v_profile.last_vote_date = v_today - 1 then
    v_streak := v_profile.streak + 1;
  else
    v_streak := 1;
  end if;

  update public.profiles set
    points = points + 10,
    streak = v_streak,
    longest_streak = greatest(longest_streak, v_streak),
    last_vote_date = v_today
  where id = v_user;

  -- Vote-count achievements.
  select count(*) into v_votes from public.votes where user_id = v_user;
  select count(distinct a.category) into v_categories
    from public.votes v join public.artworks a on a.id = v.artwork_id
    where v.user_id = v_user;

  if v_votes >= 1 then
    v_achievement_points := public.award_achievement(v_user, 'first-vote');
    if v_achievement_points > 0 then v_awarded := array_append(v_awarded, 'first-vote'); v_points := v_points + v_achievement_points; end if;
  end if;
  if v_votes >= 10 then
    v_achievement_points := public.award_achievement(v_user, 'ten-votes');
    if v_achievement_points > 0 then v_awarded := array_append(v_awarded, 'ten-votes'); v_points := v_points + v_achievement_points; end if;
  end if;
  if v_votes >= 50 and v_categories >= 5 then
    v_achievement_points := public.award_achievement(v_user, 'fifty-votes');
    if v_achievement_points > 0 then v_awarded := array_append(v_awarded, 'fifty-votes'); v_points := v_points + v_achievement_points; end if;
  end if;
  if v_votes >= 100 then
    v_achievement_points := public.award_achievement(v_user, 'hundred-votes');
    if v_achievement_points > 0 then v_awarded := array_append(v_awarded, 'hundred-votes'); v_points := v_points + v_achievement_points; end if;
  end if;
  if v_streak >= 3 then
    v_achievement_points := public.award_achievement(v_user, 'streak-3');
    if v_achievement_points > 0 then v_awarded := array_append(v_awarded, 'streak-3'); v_points := v_points + v_achievement_points; end if;
  end if;
  if v_streak >= 7 then
    v_achievement_points := public.award_achievement(v_user, 'streak-7');
    if v_achievement_points > 0 then v_awarded := array_append(v_awarded, 'streak-7'); v_points := v_points + v_achievement_points; end if;
  end if;

  if v_votes >= 20 then
    select count(*) into v_total_users from public.profiles where not is_blocked;
    select points into v_profile.points from public.profiles where id = v_user;
    select count(*) into v_higher_users from public.profiles where not is_blocked and points > v_profile.points;
    if v_total_users > 0 and ((v_higher_users + 1)::numeric / v_total_users) <= 0.10 then
      v_achievement_points := public.award_achievement(v_user, 'top-10');
      if v_achievement_points > 0 then v_awarded := array_append(v_awarded, 'top-10'); v_points := v_points + v_achievement_points; end if;
    end if;
  end if;

  -- Daily challenge: all five works judged today.
  v_challenge_ids := public.get_daily_challenge_ids(v_today);
  if p_artwork_id = any(v_challenge_ids) then
    select count(distinct artwork_id) into v_challenge_count
      from public.votes
      where user_id = v_user
        and artwork_id = any(v_challenge_ids)
        and (created_at at time zone 'utc')::date = v_today;

    if v_challenge_count >= coalesce(array_length(v_challenge_ids, 1), 0) then
      insert into public.daily_completions (user_id, challenge_date)
      values (v_user, v_today)
      on conflict (user_id, challenge_date) do nothing;
      if found then
        v_challenge_complete := true;
        v_bonus := 25;
        v_points := v_points + 25;
        update public.profiles set points = points + 25 where id = v_user;
      end if;
    end if;
  end if;

  select * into v_artwork from public.artworks where id = p_artwork_id;

  return jsonb_build_object(
    'ok', true,
    'yourVote', p_vote_type,
    'pointsEarned', v_points,
    'totalPoints', (select points from public.profiles where id = v_user),
    'streak', v_streak,
    'challengeComplete', v_challenge_complete,
    'challengeBonus', v_bonus,
    'newAchievements', coalesce(
      (select jsonb_agg(jsonb_build_object('id', id, 'name', name, 'points', points))
       from public.achievements where id = any(v_awarded)),
      '[]'::jsonb
    ),
    'stats', jsonb_build_object(
      'total', v_artwork.vote_count,
      'yes', v_artwork.yes_count,
      'no', v_artwork.no_count,
      'unsure', v_artwork.unsure_count
    )
  );
end;
$$;

-- ---------------------------------------------------------------------------
-- Auth trigger: create a profile when a Supabase Auth user signs up
-- ---------------------------------------------------------------------------

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_base text;
  v_username text;
  v_attempt integer := 0;
begin
  v_base := lower(regexp_replace(
    coalesce(new.raw_user_meta_data ->> 'username', split_part(coalesce(new.email, 'collector'), '@', 1)),
    '[^a-zA-Z0-9_]+', '_', 'g'
  ));
  v_base := left(coalesce(nullif(v_base, ''), 'collector'), 18);
  v_username := v_base;

  while exists (select 1 from public.profiles where lower(username) = lower(v_username)) loop
    v_attempt := v_attempt + 1;
    v_username := left(v_base, 18) || v_attempt::text;
    if v_attempt > 100 then
      v_username := left(v_base, 12) || substr(replace(gen_random_uuid()::text, '-', ''), 1, 6);
      exit;
    end if;
  end loop;

  insert into public.profiles (id, username, avatar_url)
  values (new.id, v_username, new.raw_user_meta_data ->> 'avatar_url')
  on conflict (id) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

