create or replace function public.sync_vote_counts()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    update public.artworks set
      vote_count = vote_count + 1,
      yes_count = yes_count + case when new.vote_type = 'yes' then 1 else 0 end,
      no_count = no_count + case when new.vote_type = 'no' then 1 else 0 end,
      unsure_count = unsure_count + case when new.vote_type = 'unsure' then 1 else 0 end
    where id = new.artwork_id;
  elsif tg_op = 'DELETE' then
    update public.artworks set
      vote_count = greatest(0, vote_count - 1),
      yes_count = greatest(0, yes_count - case when old.vote_type = 'yes' then 1 else 0 end),
      no_count = greatest(0, no_count - case when old.vote_type = 'no' then 1 else 0 end),
      unsure_count = greatest(0, unsure_count - case when old.vote_type = 'unsure' then 1 else 0 end)
    where id = old.artwork_id;
  end if;
  return null;
end;
$$;

drop trigger if exists votes_sync_counts on public.votes;
create trigger votes_sync_counts
  after insert or delete on public.votes
  for each row execute function public.sync_vote_counts();

create or replace function public.sync_comment_counts()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    if not new.is_hidden then
      update public.artworks set comment_count = comment_count + 1 where id = new.artwork_id;
    end if;
  elsif tg_op = 'DELETE' then
    if not old.is_hidden then
      update public.artworks set comment_count = greatest(0, comment_count - 1) where id = old.artwork_id;
    end if;
  elsif tg_op = 'UPDATE' and old.is_hidden <> new.is_hidden then
    update public.artworks
      set comment_count = greatest(0, comment_count + case when new.is_hidden then -1 else 1 end)
      where id = new.artwork_id;
  end if;
  return null;
end;
$$;

drop trigger if exists comments_sync_counts on public.comments;
create trigger comments_sync_counts
  after insert or update or delete on public.comments
  for each row execute function public.sync_comment_counts();

