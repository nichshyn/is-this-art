-- ===========================================================================
-- IS THIS ART? — production schema for Supabase / PostgreSQL
-- ===========================================================================
-- The reference app in this repository runs on local SQLite so that it works
-- with zero setup. This migration is the production equivalent for teams that
-- want Supabase Auth, Postgres and Storage.
--
-- Mapping notes:
--   local users          -> auth.users + public.profiles
--   local sessions       -> handled by Supabase Auth (no sessions table)
--   local password_resets-> handled by Supabase Auth
--   local guest votes    -> insert with the service role, guest_id set
--   local SQLite IDs     -> text IDs with prefixes, generated by prefixed_id()
--
-- Apply with the Supabase CLI:
--   supabase db push
-- or paste into the SQL editor. Run supabase/seed.sql afterwards.
-- ===========================================================================

